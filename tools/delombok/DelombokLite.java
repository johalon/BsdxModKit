import com.sun.source.tree.*;
import com.sun.source.util.*;
import javax.tools.*;
import java.nio.charset.StandardCharsets;
import java.nio.file.*;
import java.util.*;
import java.util.stream.*;

/**
 * Minimal "delombok" for environments where the lombok jar cannot be downloaded.
 * Handles: @Data @Getter @Setter @NoArgsConstructor @AllArgsConstructor @RequiredArgsConstructor @Slf4j
 * (class level; @Getter/@Setter also at field level). @EqualsAndHashCode/@ToString are ignored
 * (no equals/hashCode/toString generated). @Builder is NOT supported (only used by GUI classes).
 *
 * Usage: java DelombokLite <srcRoot> <outRoot>
 * Annotations are left in place; compile against stub lombok annotations (see stubs/).
 */
public class DelombokLite {
    public static void main(String[] args) throws Exception {
        Path in = Paths.get(args[0]), out = Paths.get(args[1]);
        List<Path> files;
        try (Stream<Path> s = Files.walk(in)) {
            files = s.filter(p -> p.toString().endsWith(".java")).collect(Collectors.toList());
        }
        JavaCompiler jc = ToolProvider.getSystemJavaCompiler();
        int changed = 0;
        for (Path f : files) {
            String src = Files.readString(f, StandardCharsets.UTF_8);
            Path dst = out.resolve(in.relativize(f));
            Files.createDirectories(dst.getParent());
            if (!src.contains("lombok")) { Files.writeString(dst, src, StandardCharsets.UTF_8); continue; }
            JavaFileObject jfo = new SimpleJavaFileObject(f.toUri(), JavaFileObject.Kind.SOURCE) {
                @Override public CharSequence getCharContent(boolean b) { return src; }
            };
            JavacTask task = (JavacTask) jc.getTask(null, null, d -> {}, List.of("-proc:none"), null, List.of(jfo));
            CompilationUnitTree cu = task.parse().iterator().next();
            SourcePositions sp = Trees.instance(task).getSourcePositions();
            TreeMap<Integer, String> inserts = new TreeMap<>(Comparator.reverseOrder());
            new TreePathScanner<Void, Void>() {
                @Override public Void visitClass(ClassTree ct, Void v) {
                    String gen = gen(ct, src, sp, cu);
                    if (!gen.isEmpty()) {
                        int end = (int) sp.getEndPosition(cu, ct) - 1; // position of closing brace
                        inserts.merge(end, gen, (a, b) -> b + a);
                    }
                    return super.visitClass(ct, v);
                }
            }.scan(cu, null);
            StringBuilder sb = new StringBuilder(src);
            for (Map.Entry<Integer, String> e : inserts.entrySet()) sb.insert(e.getKey(), e.getValue());
            Files.writeString(dst, sb.toString(), StandardCharsets.UTF_8);
            if (!inserts.isEmpty()) changed++;
        }
        System.out.println("files=" + files.size() + " changed=" + changed);
    }

    static Set<String> annNames(ModifiersTree m) {
        Set<String> s = new HashSet<>();
        for (AnnotationTree a : m.getAnnotations()) {
            String n = a.getAnnotationType().toString();
            s.add(n.substring(n.lastIndexOf('.') + 1));
        }
        return s;
    }

    static String cap(String n) { return Character.toUpperCase(n.charAt(0)) + n.substring(1); }

    static String gen(ClassTree ct, String src, SourcePositions sp, CompilationUnitTree cu) {
        Set<String> ca = annNames(ct.getModifiers());
        boolean data = ca.contains("Data");
        boolean getAll = data || ca.contains("Getter");
        boolean setAll = data || ca.contains("Setter");
        boolean noArgs = ca.contains("NoArgsConstructor");
        boolean allArgs = ca.contains("AllArgsConstructor");
        boolean reqArgs = ca.contains("RequiredArgsConstructor");
        boolean slf4j = ca.contains("Slf4j");
        String cname = ct.getSimpleName().toString();
        Set<String> methods = new HashSet<>();
        boolean hasCtor = false;
        List<VariableTree> fields = new ArrayList<>();
        for (Tree m : ct.getMembers()) {
            if (m instanceof MethodTree) {
                String n = ((MethodTree) m).getName().toString();
                if (n.equals("<init>")) hasCtor = true; else methods.add(n);
            } else if (m instanceof VariableTree) {
                VariableTree vt = (VariableTree) m;
                if (!vt.getModifiers().getFlags().contains(javax.lang.model.element.Modifier.STATIC)) fields.add(vt);
            }
        }
        if (ct.getKind() == Tree.Kind.ENUM || ct.getKind() == Tree.Kind.INTERFACE) {
            // enums: only @Getter / @RequiredArgsConstructor / @AllArgsConstructor are meaningful
        }
        StringBuilder g = new StringBuilder("\n    // ---- generated by DelombokLite ----\n");
        boolean any = false;
        if (slf4j) {
            g.append("    private static final org.slf4j.Logger log = org.slf4j.LoggerFactory.getLogger(").append(cname).append(".class);\n");
            any = true;
        }
        for (VariableTree f : fields) {
            Set<String> fa = annNames(f.getModifiers());
            String name = f.getName().toString();
            String type = src.substring((int) sp.getStartPosition(cu, f.getType()), (int) sp.getEndPosition(cu, f.getType()));
            boolean fin = f.getModifiers().getFlags().contains(javax.lang.model.element.Modifier.FINAL);
            boolean bool = type.equals("boolean");
            if (getAll || fa.contains("Getter")) {
                String gn;
                if (bool) gn = (name.startsWith("is") && name.length() > 2 && Character.isUpperCase(name.charAt(2))) ? name : "is" + cap(name);
                else gn = "get" + cap(name);
                if (!methods.contains(gn)) { g.append("    public ").append(type).append(' ').append(gn).append("() { return this.").append(name).append("; }\n"); any = true; }
            }
            if ((setAll || fa.contains("Setter")) && !fin) {
                String base = (bool && name.startsWith("is") && name.length() > 2 && Character.isUpperCase(name.charAt(2))) ? name.substring(2) : cap(name);
                String sn = "set" + base;
                if (!methods.contains(sn)) { g.append("    public void ").append(sn).append('(').append(type).append(' ').append(name).append(") { this.").append(name).append(" = ").append(name).append("; }\n"); any = true; }
            }
        }
        if (noArgs) {
            g.append("    public ").append(cname).append("() {}\n"); any = true;
        }
        List<VariableTree> allF = fields.stream().filter(f -> !(f.getModifiers().getFlags().contains(javax.lang.model.element.Modifier.FINAL) && f.getInitializer() != null)).collect(Collectors.toList());
        List<VariableTree> reqF = fields.stream().filter(f -> f.getModifiers().getFlags().contains(javax.lang.model.element.Modifier.FINAL) && f.getInitializer() == null).collect(Collectors.toList());
        if (allArgs && !(allF.isEmpty() && noArgs)) { g.append(ctor(cname, allF, src, sp, cu, ct)); any = true; }
        boolean implicitReq = data && !hasCtor && !noArgs && !allArgs && !reqArgs;
        if ((reqArgs || implicitReq) && !(reqF.isEmpty() && noArgs) && !(allArgs && reqF.size() == allF.size())) { g.append(ctor(cname, reqF, src, sp, cu, ct)); any = true; }
        return any ? g.toString() : "";
    }

    static String ctor(String cname, List<VariableTree> fs, String src, SourcePositions sp, CompilationUnitTree cu, ClassTree ct) {
        boolean isEnum = ct.getKind() == Tree.Kind.ENUM;
        StringBuilder s = new StringBuilder("    ").append(isEnum ? "" : "public ").append(cname).append('(');
        StringBuilder body = new StringBuilder();
        for (int i = 0; i < fs.size(); i++) {
            VariableTree f = fs.get(i);
            String type = src.substring((int) sp.getStartPosition(cu, f.getType()), (int) sp.getEndPosition(cu, f.getType()));
            if (i > 0) s.append(", ");
            s.append(type).append(' ').append(f.getName());
            body.append(" this.").append(f.getName()).append(" = ").append(f.getName()).append(';');
        }
        return s.append(") {").append(body).append(" }\n").toString();
    }
}
