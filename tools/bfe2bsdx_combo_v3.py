def min_ratio_mod(tech, bfe_power, bfe_min):
    """modified の 最低値 / 表示威力。"""
    if tech in MOD_MIN_SET:
        r = MOD_MIN_SET[tech][0]
    else:
        d = LATE.get(tech)
        if d is None:
            r = min(0.6, bfe_min / bfe_power) if bfe_power > 0 else 0.1
        else:
            r = 0.6 if d <= -0.20 else 0.3 if d <= -0.05 else 0.1
    if tech in _MT.p('TACKLE_MIN', 'weapons', ()):      # 11/13: タックル類の最低値を半分に（tools/modified_tweaks.py TACKLE_MIN）
        r *= _MT.p('TACKLE_MIN', 'mul')
    return r


def min_mod(tech, bfe_power, bfe_min, power_mul=1.0):
    """modified の最低値。表示威力 = floor(round(BFE 威力 / 4) x power_mul x1.5)（NONFC_POWER_MOD を渡す）。"""
    disp = int(max(1, round(round(bfe_power / 4) * power_mul)) * 1.5)
    return max(1, round(disp * min_ratio_mod(tech, bfe_power, bfe_min)))


def min_3b(bfe_min):
    return max(1, round(bfe_min * 3 / 8))


