#!/usr/bin/env python3
"""bfe_waz.py - BALDR FORCE EXE .WAZ / Tama.dat / .CPU parser with named fields.

Structure validated on TOORU.WAZ / akira.waz / Tama.dat / TOORU.CPU / akira.cpu (all parse to EOF).
Field names/meanings come from tools/bfe_waz_fields.json (generated by gen_bfe_waz_fields.py from the
editor dialogs + code of the unprotected BaldrForce.exe; see notes/07_bfe_exe_analysis.md).

WAZ file : u16 skillCount
           skill: skill_header 0x6C (raw MSVC struct; 0xCC = debug fill)
                  phase[phase_count]: phase 0x18C (n_events at +0x188) + spr_event 48B × n_events
CPU file : cpu_header 0x32; u16 n; cpu_move 96B×n; u16 n; {4B,u16 m,cpu_attack 48B×m}×n; u16 n; cpu_counter 24B×n

Usage:
  bfe_waz.py <file.waz> [out.json] [--raw]     named JSON (parse() API unchanged for old callers)
  bfe_waz.py <file.waz> --summary [--equip EquipmentInfo.DAT]   one line per skill
  bfe_waz.py <file.cpu> [out.json]             CPU (AI) file -> named JSON
"""
import json, os, struct, sys

HDR = 0x6C
PH_FIXED = 392          # bytes before the u32 that holds n_events (kept for old callers)
PH_SIZE = 0x18C
EV = 48
FIELDS = json.load(open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'bfe_waz_fields.json'), encoding='utf-8'))
ST = FIELDS['structs']
SE = [n for n, _ in FIELDS['enums']['se']['names']]
SCAL = {'u8': '<B', 'i8': '<b', 'u16': '<H', 'i16': '<h', 'u32': '<I', 'i32': '<i',
        'bits8': '<B', 'bits16': '<H', 'bits32': '<I'}


def parse(d):
    """raw split (unchanged API): list of {index, offset, size, name, header, phases[{fixed, events[]}]}"""
    n = struct.unpack_from('<H', d, 0)[0]
    p = 2
    skills = []
    for i in range(n):
        st = p
        hdr = d[p:p + HDR]
        nph = hdr[0x6A]
        p += HDR
        phases = []
        for k in range(nph):
            fixed = d[p:p + PH_FIXED]
            ne = d[p + 0x188]
            evs = [d[p + PH_SIZE + EV * j:p + PH_SIZE + EV * (j + 1)] for j in range(ne)]
            phases.append(dict(fixed=fixed, block=d[p:p + PH_SIZE], events=evs))
            p += PH_SIZE + EV * ne
        skills.append(dict(index=i, offset=st, size=p - st,
                           name=hdr[:40].split(b'\0')[0].decode('cp932', 'replace'),
                           header=hdr, phases=phases))
    if p != len(d):
        raise ValueError('did not reach EOF: %d != %d' % (p, len(d)))
    return skills


def _val(typ, b, o):
    if typ.startswith('struct:'):
        nm = typ[7:]
        if nm.endswith(']'):
            nm, cnt = nm[:-1].split('[')
            sz = ST[nm]['size']
            return [decode(nm, b, o + sz * i) for i in range(int(cnt))]
        return decode(nm, b, o)
    if typ.startswith('char['):
        n = int(typ[5:-1])
        return b[o:o + n].split(b'\0')[0].decode('cp932', 'replace')
    if typ == 'i16[2]+i32':
        return list(struct.unpack_from('<hhi', b, o))
    if '[' in typ:
        base, n = typ[:-1].split('[')
        f = SCAL[base]
        sz = struct.calcsize(f)
        return [struct.unpack_from(f, b, o + sz * i)[0] for i in range(int(n))]
    return struct.unpack_from(SCAL[typ], b, o)[0]


def decode(name, b, off=0):
    out = {}
    for f in ST[name]['fields']:
        if f['name'].startswith('pad'):
            continue
        v = _val(f['type'], b, off + f['off'])
        if f['type'].startswith('bits') and 'bits' in f:
            out[f['name']] = v
            on = [f['bits'][i] for i in range(len(f['bits'])) if v >> i & 1]
            if on:
                out[f['name'] + '_names'] = on
        else:
            out[f['name']] = v
        if f.get('enum') == 'se' and isinstance(v, int) and 0 <= v < len(SE):
            out[f['name'] + '_name'] = SE[v]
    return out


def _compact(x):
    """drop 'unused' sub-blocks (all-zero / all -32768 ranges) to keep JSON readable"""
    if isinstance(x, dict):
        return {k: _compact(v) for k, v in x.items()}
    return x


def named(d, raw=False):
    out = []
    for s in parse(d):
        h = decode('skill_header', s['header'])
        sk = dict(index=s['index'], offset=s['offset'], size=s['size'], header=h, phases=[])
        if raw:
            sk['header_hex'] = s['header'].hex()
        for ph in s['phases']:
            p = decode('phase', ph['block'])
            p['events'] = [decode('spr_event', e) for e in ph['events']]
            if raw:
                p['block_hex'] = ph['block'].hex()
                for e, r in zip(p['events'], ph['events']):
                    e['raw'] = r.hex()
            sk['phases'].append(p)
        out.append(sk)
    return out


def parse_cpu(d):
    o = dict(header=decode('cpu_header', d, 0))
    p = 0x32
    n = struct.unpack_from('<h', d, p)[0]; p += 2
    o['move'] = [decode('cpu_move', d, p + 96 * i) for i in range(n)]; p += 96 * n
    n = struct.unpack_from('<h', d, p)[0]; p += 2
    combos = []
    for i in range(n):
        e = d[p:p + 4]; p += 4
        m = struct.unpack_from('<h', d, p)[0]; p += 2
        combos.append(dict(head=e.hex(), interrupt=e[0], attacks=[decode('cpu_attack', d, p + 48 * k) for k in range(m)]))
        p += 48 * m
    o['combo'] = combos
    n = struct.unpack_from('<h', d, p)[0]; p += 2
    o['counter'] = [decode('cpu_counter', d, p + 24 * i) for i in range(n)]; p += 24 * n
    if p != len(d):
        raise ValueError('CPU did not reach EOF: %d != %d' % (p, len(d)))
    return o


def equip_names(path):
    b = open(path, 'rb').read()
    return [b[i:i + 240].split(b'\0')[0].decode('cp932', 'replace') for i in range(0, len(b), 240)]


def summary(d):
    rows = []
    for s in named(d):
        h = s['header']
        pw, hits, tama, se = [], [], [], []
        frames = 0
        for p in s['phases']:
            hb = p['hit']
            if hb['hits_mech'] not in (0, 254):
                pw.append(hb['power']); hits.append(hb['hits_mech'])
            if p['fire']['tama'] >= 0:
                tama.append(p['fire']['tama'])
            for e in p['events']:
                if e['se_play'] >= 0:
                    se.append(SE[e['se_play']] if e['se_play'] < len(SE) else e['se_play'])
                if e['anim_type'] == 0:
                    frames += e['wait'][0]
        rows.append(dict(i=s['index'], name=h['name'], group=h['group'], kind=h['kind'], heat=h['heat'], exp=h['exp'],
                         phases=h['phase_count'], power=pw, hits=hits, tama=tama, se=se, fixed_frames=frames))
    return rows


def main(a):
    if len(a) < 2:
        print(__doc__); return 1
    d = open(a[1], 'rb').read()
    raw = '--raw' in a
    outp = [x for x in a[2:] if not x.startswith('--') and not a[a.index(x) - 1] == '--equip']
    if a[1].lower().endswith('.cpu'):
        o = parse_cpu(d)
        print('%s: move %d, combo %d, counter %d' % (a[1], len(o['move']), len(o['combo']), len(o['counter'])))
        if outp:
            json.dump(o, open(outp[0], 'w'), ensure_ascii=False, indent=1)
        return 0
    if '--summary' in a:
        rows = summary(d)
        for r in rows:
            print('%3d %-24s g%d k%d OH%3d EXP%4d ph%2d pow%s hits%s tama%s se%s' % (
                r['i'], r['name'], r['group'], r['kind'], r['heat'], r['exp'], r['phases'], r['power'], r['hits'], r['tama'], r['se'][:3]))
        return 0
    out = named(d, raw)
    print('%s: %d skills, %d phases total' % (a[1], len(out), sum(len(s['phases']) for s in out)))
    if outp:
        json.dump(out, open(outp[0], 'w'), ensure_ascii=False, indent=1)
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
